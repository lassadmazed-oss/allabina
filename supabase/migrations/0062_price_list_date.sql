-- ============================================================
-- 0062_price_list_date.sql · تاريخ قائمة الأسعار
-- ============================================================
-- الكاتالوج يعرض السعر، والسعر بلا تاريخه لا يُراجَع: زائرٌ يقرأ رقماً
-- لا يعرف إن كان رقم اليوم أو رقم العام الفائت.
--
-- ولماذا إعداد لا عمود محسوب؟ لأنّ articles.updated_at لا يصلح:
-- المُطلِق articles_touch يحرّكه عند **أيّ** تحديث، وضغطةُ «نشر» تحديث.
-- فأوّل نشرٍ يجعل الصفحة تقول «الأسعار محيَّنة اليوم» وما تبدّل منها
-- سنتيم — تاريخٌ صحيح تقنياً وكذبةٌ على الشاشة.
--
-- الأولوية لآخر تغيير سعر فعلي في article_price_history (المُطلِق
-- يكتبه حين يختلف السعر وحده، لا حين يُنشَر السطر). وما دام الجدول
-- فارغاً — ولا سعر من الـ333 تبدّل بعد البذرة — يُعرض هذا التاريخ.
--
-- 2026-09-07: يوم ما ثُبّتت فيه أسعار البذرة (0015_bordereau_seed).
-- وهي أسعار استرشادية معيَّرة على السوق لا عروضاً متثبَّتاً منها، كما
-- تقوله البذرة نفسها في رأسها. من يراجع سعراً يبدّل هذا التاريخ معه.
-- ============================================================

insert into app_settings (key, value, description) values
  ('catalog.price_list_date', '"2026-09-07"'::jsonb,
   'تاريخ قائمة الأسعار المعروض في الكاتالوج العمومي (YYYY-MM-DD). يُستعمل ما دام لا تغيير سعر مسجَّل في article_price_history.')
on conflict (key) do nothing;
