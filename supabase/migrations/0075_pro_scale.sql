-- القيد من 0001: `desired_area_m2 between 40 and 400`. وهو حدّ **دار**:
-- كُتب يوم كانت المنصّة وساطةً سكنيّة. ومن 15/11/2026 يدخل المحترف:
-- عمارة من اثنتي عشرة شقّة ألفٌ ومئتا متر، ومستودعٌ أكثر.
--
-- وقع فعلاً: عمارة 1 200 م² رفضتها القاعدة، والحريف قرأ «ما نجّمناش
-- نبعثو» بلا أن يعرف أنّ الرقم هو المشكل. والقيد كان محقّاً في زمنه.
--
-- الحدّ الجديد يتّسع للمحترف ويبقى يمسك غلطة لوحة المفاتيح: عشرون ألف
-- متر مغطّى سقفٌ لا يبلغه مشروعٌ في صفاقس، وعشرة أمتار أرضيةُ محلٍّ
-- صغير.
-- ============================================================

alter table housing_requests
  drop constraint if exists housing_requests_desired_area_m2_check;

alter table housing_requests
  add constraint housing_requests_desired_area_m2_check
  check (desired_area_m2 is null or (desired_area_m2 between 10 and 20000));
