-- =====================================================================
-- 0034 — مساحة الأرض المطلوبة في مسار «أرض ودار»
--
-- من يبني فوق أرضه يصرّح بمساحة أرضه في request_land: قطعة يملكها،
-- لها رسم وماء وكهرباء. ومن يطلب «أرض ودار» ما عندوش أرض بعدُ — عندو
-- مقاس يدوّر عليه. الاثنان «مساحة أرض» بالاسم، ومختلفان في المعنى:
-- الأولى واقع مسجَّل، والثانية معيار بحث.
--
-- خلطهما في request_land كان يعطي الفريق قطعة أرض لا وجود لها، بلا
-- رسم ولا مرافق. فمعيار البحث يسكن مع بقية معايير البحث في المطلب،
-- بجانب desired_area_m2 (مساحة المبني المطلوبة).
-- =====================================================================

alter table housing_requests
  add column if not exists desired_land_m2 int
  check (desired_land_m2 between 50 and 5000);

comment on column housing_requests.desired_land_m2 is
  'مساحة الأرض التي يدوّر عليها (مسار أرض ودار) — معيار بحث لا قطعة مملوكة. القطعة المملوكة في request_land.';
