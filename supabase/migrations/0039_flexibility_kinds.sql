-- «على شنوّة تنجّم تتنازل؟» كانت ستّة خيارات. الاثنان الأكثر واقعية في
-- صفاقس لم يكونا فيها:
--   levels — أرضي اليوم وطابق غداً: أكثر ما يُبنى فعلاً في الأحياء الجديدة
--   phased — الهيكل والضروري أوّلاً، والباقي كي تتيسّر: طريقة من لا يقترض
-- كلاهما يخفّض الميزانية الأولى دون أن يخفّض الدار النهائية.
-- ============================================================

alter type flexibility_kind add value if not exists 'levels';
alter type flexibility_kind add value if not exists 'phased';
